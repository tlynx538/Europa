import { test, expect, type APIRequestContext, type Page } from '@playwright/test'

const api = `http://127.0.0.1:${process.env.EUROPA_TEST_PORT || '18000'}/api`
async function seed(request: APIRequestContext, title: string, code = 'print(42)', cellType = 'code') {
  const response = await request.post(`${api}/notebooks`, { data: { title } }); expect(response.status()).toBe(201)
  const doc = await response.json(), id = doc.metadata.europa.notebook_id
  const cellResponse = await request.post(`${api}/notebooks/${id}/cells`, { data: { revision: 1, source: code, cell_type: cellType } }); expect(cellResponse.status()).toBe(201)
  return { id, doc: await cellResponse.json() }
}
async function open(page: Page, id: string) {
  await page.goto(`/notebooks/${id}`)
  await expect(page).toHaveURL(new RegExp(`/notebooks/${id}$`))
  await expect(page.locator('.cell').first()).toBeVisible()
}
async function panel(page: Page, name: 'Roadmap' | 'Discussion') {
  if (name === 'Discussion') { await expect(page.locator('.message-composer')).toBeVisible(); return }
  if (await page.locator('#roadmap').isVisible()) return
  await page.getByRole('menubar').getByRole('menuitem', { name: 'View' }).click()
  await page.getByRole('menuitemcheckbox', { name: 'Roadmap panel' }).click()
  await expect(page.locator('#roadmap')).toBeVisible()
}
async function projectReady(page: Page, id: string) {
  await expect(page.locator('.project-settings-dialog').getByLabel('Project', { exact: true })).toHaveValue(id)
}
async function canonical(request: APIRequestContext, id: string) {
  const response = await request.get(`${api}/notebooks/${id}/conversation`); expect(response.status()).toBe(200); return response.json()
}
async function disableAutosave(page: Page) {
  await page.getByRole('menubar').getByRole('menuitem', { name: 'View' }).click()
  const autosave = page.getByRole('menuitemcheckbox', { name: 'Autosave' })
  if (await autosave.getAttribute('aria-checked') === 'true') await autosave.click()
  else await expect(autosave).toHaveAttribute('aria-checked', 'false')
  await page.keyboard.press('Escape')
}
async function post(request: APIRequestContext, path: string, body: object) {
  const response = await request.post(`${api}${path}`, { data: { operation_id: crypto.randomUUID(), ...body } }); expect([200, 201, 202]).toContain(response.status()); return response.json()
}

test('toolbar insertion appends after messages even when an earlier cell is selected', async ({ page, request }) => {
  const { id, doc } = await seed(request, 'Continuous stream insertion')
  const inserted = await request.post(`${api}/notebooks/${id}/cells`, { data: { revision: doc.metadata.europa.revision, source: 'second', cell_type: 'code' } })
  expect(inserted.status()).toBe(201)
  const before = await inserted.json()
  await open(page, id)
  await panel(page, 'Discussion')
  await page.getByLabel('Message', { exact: true }).fill('Before new cell')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  const prior = page.locator('article.message').filter({ hasText: 'Before new cell' })
  await expect(prior).toBeVisible()
  await page.locator('.cell').first().focus()
  await page.getByRole('toolbar', { name: 'Notebook commands' }).getByRole('button', { name: 'Insert cell' }).click()
  await expect(page.locator('.cell')).toHaveCount(3)
  const saved = await (await request.get(`${api}/notebooks/${id}`)).json()
  const appended = page.locator(`#cell-${saved.cells[2].id}`)
  await expect(appended).toHaveClass(/selected/)
  await expect.poll(() => page.evaluate(cell => {
    const bounds = document.getElementById(`cell-${cell}`)!.getBoundingClientRect()
    const composer = document.querySelector('.composer-shell')!.getBoundingClientRect()
    const top = document.querySelector('.appbar')!.getBoundingClientRect().bottom
    return bounds.top >= top && bounds.top < composer.top
  }, saved.cells[2].id)).toBe(true)
  expect(saved.cells.slice(0, 2).map((cell: { id: string }) => cell.id)).toEqual(before.cells.map((cell: { id: string }) => cell.id))
  await expect.poll(() => page.evaluate(() => [...document.querySelectorAll('.cell, article.message')].map(node =>
    node.classList.contains('cell') ? node.id : node.textContent?.includes('Before new cell') ? 'before' : 'other').filter(item => item !== 'other').slice(-2))).toEqual(['before', `cell-${saved.cells[2].id}`])
  await page.getByLabel('Message', { exact: true }).fill('After new cell')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.locator('.cell-conversation').last()).toContainText('After new cell')
  await page.reload()
  await expect(page.locator('.cell')).toHaveCount(3)
  await expect(prior).toBeVisible()
  await expect(page.locator('.cell-conversation').last()).toContainText('After new cell')
})

