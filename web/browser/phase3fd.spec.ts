import { expect, test } from '@playwright/test'

const api = `http://127.0.0.1:${process.env.EUROPA_TEST_PORT || '18000'}/api`

test('menus are single-open, keyboard accessible and bounded by the viewport', async ({ page, request }) => {
  const created = await request.post(`${api}/notebooks`, { data: { title: 'Menu accessibility' } })
  const id = (await created.json()).metadata.europa.notebook_id
  await page.setViewportSize({ width: 640, height: 720 })
  await page.goto(`/notebooks/${id}`)
  await page.getByRole('heading', { name: 'Menu accessibility' }).waitFor()
  const menus = page.locator('.appbar-more')
  await menus.filter({ has: page.locator('summary', { hasText: 'File' }) }).locator('summary').click()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('button', { name: 'Notebooks', exact: true })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('button', { name: 'New notebook…' })).toBeFocused()
  await menus.filter({ has: page.locator('summary', { hasText: 'View' }) }).locator('summary').click()
  await expect(menus.filter({ has: page.locator('summary', { hasText: 'File' }) })).not.toHaveAttribute('open')
  await expect(menus.filter({ has: page.locator('summary', { hasText: 'View' }) })).toHaveAttribute('open', '')
  await page.keyboard.press('Escape')
  await expect(menus.filter({ has: page.locator('summary', { hasText: 'View' }) })).not.toHaveAttribute('open')
  await expect(menus.filter({ has: page.locator('summary', { hasText: 'View' }) }).locator('summary')).toBeFocused()
  await page.getByText('Help', { exact: true }).click()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('button', { name: 'Keyboard shortcuts' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('dialog', { name: 'Keyboard shortcuts' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: 'Keyboard shortcuts' })).not.toBeVisible()
  await page.getByText('Kernel', { exact: true }).click()
  await expect(page.getByRole('button', { name: 'Kernel information' })).toBeVisible()
  await page.getByRole('button', { name: 'Kernel information' }).click()
  await expect(page.getByRole('dialog', { name: 'Kernel information' })).toContainText('Restart and shutdown are unavailable')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: 'Kernel information' })).not.toBeVisible()
  await page.getByText('Kernel', { exact: true }).click()
  const box = await menus.filter({ has: page.locator('summary', { hasText: 'Kernel' }) }).locator(':scope > div').boundingBox()
  expect(box).not.toBeNull()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(640)
  await page.locator('.notebook-surface').click({ position: { x: 10, y: 300 } })
  await expect(menus.filter({ has: page.locator('summary', { hasText: 'Kernel' }) })).not.toHaveAttribute('open')
  await menus.filter({ has: page.locator('summary', { hasText: 'File' }) }).locator('summary').click()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Roadmap', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Project and roadmap' })).toBeVisible()
  await expect(page.locator('.appbar-more[open]')).toHaveCount(0)
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 320, height: 720 })
  await menus.filter({ has: page.locator('summary', { hasText: 'Help' }) }).locator('summary').click()
  const mobileBox = await menus.filter({ has: page.locator('summary', { hasText: 'Help' }) }).locator(':scope > div').boundingBox()
  expect(mobileBox).not.toBeNull()
  expect(mobileBox!.x).toBeGreaterThanOrEqual(0)
  expect(mobileBox!.x + mobileBox!.width).toBeLessThanOrEqual(320)
})

test('primary toolbar stays focused, secondary actions remain in menus and disabled edits explain why', async ({ page, request }) => {
  const created = await request.post(`${api}/notebooks`, { data: { title: 'Toolbar focus' } })
  const id = (await created.json()).metadata.europa.notebook_id
  await request.post(`${api}/notebooks/${id}/cells`, { data: { revision: 1, cell_type: 'code', source: 'print(42)' } })
  await page.goto(`/notebooks/${id}`)
  await expect(page.locator('.cell')).toHaveCount(1)
  const toolbar = page.getByRole('toolbar', { name: 'Notebook commands' })
  for (const name of ['Save notebook', 'Insert cell', 'Run selected cell', 'Interrupt selected execution']) await expect(toolbar.getByRole('button', { name })).toHaveCount(1)
  for (const name of ['Cut cell', 'Copy cell', 'Paste cell']) await expect(toolbar.getByRole('button', { name })).toHaveCount(0)
  await expect(toolbar.getByLabel('Autosave')).toHaveCount(0)
  await expect(toolbar.getByText('Kernel:')).toHaveCount(0)
  await page.locator('.cell .cm-content').click()
  await page.locator('.appbar-more').filter({ has: page.locator('summary', { hasText: 'View' }) }).locator('summary').click()
  await page.getByLabel('Autosave', { exact: true }).uncheck()
  await page.keyboard.press('Escape')
  await page.locator('.cell .cm-content').click()
  await page.keyboard.insertText(' # draft')
  await page.locator('.appbar-more').filter({ has: page.locator('summary', { hasText: 'Edit' }) }).locator('summary').click()
  const cut = page.getByRole('button', { name: 'Cut cell' })
  await expect(cut).toBeDisabled()
  await expect(cut).toHaveAttribute('title', /Save all drafts before cutting/)
  await expect(page.locator('.appbar-more[open] p')).toHaveCount(0)
})

test('roadmap shows progress before project settings and an explicit no-roadmap state', async ({ page, request }) => {
  const notebook = await (await request.post(`${api}/notebooks`, { data: { title: 'Roadmap focus' } })).json()
  const id = notebook.metadata.europa.notebook_id
  const project = await (await request.post(`${api}/projects`, { data: { operation_id: crypto.randomUUID(), title: 'Roadmap context' } })).json()
  await request.post(`${api}/projects/${project.id}/notebooks`, { data: { operation_id: crypto.randomUUID(), revision: 1, notebook_id: id } })
  await page.goto(`/notebooks/${id}`)
  await page.getByRole('button', { name: 'Roadmap', exact: true }).click()
  await expect(page.getByText('No roadmap for this project yet.')).toBeVisible()
  const panel = page.locator('#roadmap')
  await expect(panel.getByRole('button', { name: 'Refresh project history' })).toBeHidden()
  await expect(panel.getByRole('button', { name: 'Create roadmap' })).toBeHidden()
  await panel.locator('.project-settings > summary').click()
  await expect(panel.getByRole('button', { name: 'Create roadmap' })).toBeVisible()
  await request.post(`${api}/roadmaps`, { data: { operation_id: crypto.randomUUID(), project_id: project.id, objective: 'Review receipts', tasks: [{ id: 'review', title: 'Check execution', acceptance_criteria: ['Read receipt'] }] } })
  await panel.getByRole('button', { name: 'Refresh project history' }).click()
  await expect(panel.getByRole('progressbar', { name: 'Overall project progress' })).toBeVisible({ timeout: 20000 })
  await expect(panel.getByRole('button', { name: /Check execution/ })).toBeVisible()
  await expect(panel.getByRole('button', { name: 'Create roadmap' })).toBeHidden()
})

test('paused notebook shortcuts never submit execution or advance selection', async ({ page, request }) => {
  const created = await request.post(`${api}/notebooks`, { data: { title: 'Paused shortcuts' } })
  const id = (await created.json()).metadata.europa.notebook_id
  const first = await request.post(`${api}/notebooks/${id}/cells`, { data: { revision: 1, source: 'print(42)', cell_type: 'code' } })
  const firstId = (await first.json()).cells[0].id
  await request.post(`${api}/notebooks/${id}/cells`, { data: { revision: 2, source: 'print(43)', cell_type: 'code' } })
  await page.goto(`/notebooks/${id}`)
  await expect(page.locator('.cell')).toHaveCount(2)
  await page.locator('.appbar-more').filter({ has: page.locator('summary', { hasText: 'View' }) }).locator('summary').click()
  await page.getByLabel('Autosave', { exact: true }).uncheck()
  await page.keyboard.press('Escape')
  await page.locator('.cell .cm-content').first().click()
  await page.keyboard.insertText(' # draft')
  await page.getByRole('button', { name: 'Compare with saved notebook' }).click()
  await expect(page.getByRole('status')).toContainText('Autosave paused')
  const executions: string[] = []
  page.on('request', r => { if (r.method() === 'POST' && r.url().includes('/execute')) executions.push(r.url()) })
  await page.locator('.cell .cm-content').first().click()
  await page.keyboard.press('Shift+Enter')
  await expect(page.locator(`#cell-${firstId}`)).toHaveClass(/selected/)
  await page.keyboard.press('ControlOrMeta+Enter')
  expect(executions).toHaveLength(0)
  await expect(page.getByRole('toolbar', { name: 'Notebook commands' }).getByRole('button', { name: 'Run selected cell' })).toBeDisabled()
})

test('activity distinguishes an empty project from persisted owner history', async ({ page, request }) => {
  const created = await request.post(`${api}/projects`, { data: { operation_id: crypto.randomUUID(), title: 'Activity owner' } })
  const project = await created.json()
  await page.goto('/activity')
  await page.getByLabel('Project').selectOption(project.id)
  await expect(page.getByText('No activity recorded for this project.')).toBeVisible()
  const recorded = await request.post(`${api}/projects/${project.id}/activities`, { data: { operation_id: crypto.randomUUID(), project_id: project.id, summary: 'Owner reviewed recovery', result: 'recorded' } })
  expect(recorded.status()).toBe(201)
  await page.reload()
  await page.getByLabel('Project').selectOption(project.id)
  await expect(page.getByText('Owner reviewed recovery')).toBeVisible()
  await expect(page.getByText('No activity recorded for this project.')).toHaveCount(0)
})
