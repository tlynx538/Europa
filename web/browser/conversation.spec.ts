import { expect, test, type APIRequestContext, type Page } from '../browserFixtures'

const api = `http://127.0.0.1:${process.env.EUROPA_TEST_PORT || '18000'}/api`
async function create(request: APIRequestContext, title: string) {
  const response = await request.post(`${api}/notebooks`, { data: { title } })
  expect(response.status()).toBe(201)
  return (await response.json()).metadata.europa.notebook_id as string
}
async function canonical(request: APIRequestContext, id: string) {
  const response = await request.get(`${api}/notebooks/${id}/conversation`)
  expect(response.status()).toBe(200)
  return response.json()
}
async function open(page: Page, id: string) {
  await page.goto(`/notebooks/${id}`)
  await expect(page.locator('.message-composer')).toBeVisible()
  await expect(page.getByLabel('Message', { exact: true })).toBeEnabled()
}

test('inline cell comment and reply keep the thread readable without native dialogs', async ({ page, request }) => {
  const id = await create(request, 'Inline comment workflow')
  const added = await request.post(`${api}/notebooks/${id}/cells`, { data: { revision: 1, cell_type: 'code', source: 'print(42)' } })
  expect(added.status()).toBe(201)
  const cell = (await added.json()).cells[0].id
  const created = await request.post(`${api}/projects`, { data: { operation_id: crypto.randomUUID(), title: 'Comment project' } })
  expect(created.status()).toBe(201)
  const project = await created.json()
  expect((await request.post(`${api}/projects/${project.id}/notebooks`, { data: { operation_id: crypto.randomUUID(), revision: 1, notebook_id: id } })).status()).toBe(200)
  const dialogs: string[] = []
  page.on('dialog', dialog => { dialogs.push(dialog.message()); void dialog.dismiss() })
  await open(page, id)
  await expect(page.locator('.project-settings-dialog').getByLabel('Project', { exact: true })).toHaveValue(project.id)
  await page.locator(`#cell-${cell}`).focus()
  await page.getByRole('button', { name: 'Comment on cell' }).click()
  const comment = page.getByRole('textbox', { name: /Comment · Cell 1/ })
  await expect(comment).toBeFocused()
  await comment.fill('First line\nSecond line')
  await page.getByRole('button', { name: 'Post comment' }).click()
  const card = page.locator('.cell-comment').filter({ hasText: 'First line' })
  await expect(card).toContainText('Second line')
  const desktop = await card.boundingBox()
  expect(desktop?.width).toBeGreaterThan(600)
  await card.getByRole('button', { name: 'Reply to comment' }).click()
  await page.getByRole('textbox', { name: /Reply · Cell 1/ }).fill('Owner follow-up')
  await card.getByRole('button', { name: 'Post reply' }).click()
  await expect(card.locator('.comment-reply')).toContainText('Owner follow-up')
  await expect(card.locator('.comment-reply .message-meta')).toContainText('user')
  await page.setViewportSize({ width: 390, height: 844 })
  const mobile = await card.boundingBox()
  expect(mobile).not.toBeNull()
  expect(mobile!.x).toBeGreaterThanOrEqual(0)
  expect(mobile!.x + mobile!.width).toBeLessThanOrEqual(390)
  expect(mobile!.width).toBeGreaterThan(220)
  await page.reload()
  await expect(page.locator('.cell-comment .comment-reply')).toContainText('Owner follow-up')
  expect(dialogs).toEqual([])
})

test('standalone canonical ID and user messages persist across membership, reload and reopen', async ({ page, request }) => {
  const id = await create(request, 'Standalone conversation')
  const original = await canonical(request, id)
  expect(original.notebook_id).toBe(id)
  await open(page, id)
  await expect(page.getByRole('button', { name: /New conversation|Start discussion|Discussion/i })).toHaveCount(0)
  await page.getByLabel('Message', { exact: true }).fill('Standalone saved message')
  await page.getByRole('button', { name: 'Send' }).click()
  await expect(page.locator('article.message[data-author="user"]')).toContainText('Standalone saved message')
  const projectResponse = await request.post(`${api}/projects`, { data: { operation_id: crypto.randomUUID(), title: 'Membership does not own chat' } })
  expect(projectResponse.status()).toBe(201)
  const project = await projectResponse.json()
  expect((await request.post(`${api}/projects/${project.id}/notebooks`, { data: { operation_id: crypto.randomUUID(), revision: 1, notebook_id: id } })).status()).toBe(200)
  await page.reload()
  await expect(page.locator('article.message[data-author="user"]')).toContainText('Standalone saved message')
  expect((await canonical(request, id)).id).toBe(original.id)
  await page.goto('/notebooks')
  await open(page, id)
  await expect(page.locator('article.message[data-author="user"]')).toContainText('Standalone saved message')
  const history = await (await request.get(`${api}/conversations/${original.id}/messages`)).json()
  expect(history.items).toHaveLength(1)
  expect(history.items[0].data.author_role).toBe('user')
  expect((await canonical(request, id)).id).toBe(original.id)
})

test('selected cell reference is explicit, server scoped and never executes or silently retargets', async ({ page, request }) => {
  const id = await create(request, 'Message reference')
  const created = await request.post(`${api}/notebooks/${id}/cells`, { data: { revision: 1, cell_type: 'code', source: 'print(37)' } })
  expect(created.status()).toBe(201)
  const doc = await created.json(), cell = doc.cells[0].id
  const original = await canonical(request, id)
  const executions: string[] = []
  page.on('request', sent => { if (sent.method() === 'POST' && sent.url().includes('/execute')) executions.push(sent.url()) })
  await open(page, id)
  await page.locator(`#cell-${cell}`).focus()
  await page.getByRole('button', { name: 'Attach selected cell' }).click()
  await expect(page.locator('.reference-chip')).toContainText('Cell 1')
  await page.getByLabel('Message', { exact: true }).fill('Inspect saved code')
  const sent = page.waitForResponse(response => response.url().endsWith(`/conversations/${original.id}/messages`) && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Send' }).click()
  expect((await sent).status()).toBe(201)
  const messages = (await (await request.get(`${api}/conversations/${original.id}/messages`)).json()).items
  expect(messages).toHaveLength(1)
  expect(messages[0].data).toMatchObject({ author_role: 'user', notebook_id: id, cell_id: cell, document_revision: doc.metadata.europa.revision, placement_after_cell_id: cell })
  expect(executions).toHaveLength(0)
  expect((await (await request.get(`${api}/notebooks/${id}`)).json()).cells[0]).toMatchObject({ id: cell, source: 'print(37)', outputs: [] })
  await page.reload()
  await expect(page.locator('article.message[data-author="user"]')).toContainText('Inspect saved code')
  await page.locator(`#cell-${cell}`).focus()
  await page.getByRole('button', { name: 'Attach selected cell' }).click()
  await page.getByLabel('Message', { exact: true }).fill('Preserve this draft')
  await page.reload()
  await expect(page.getByLabel('Message', { exact: true })).toHaveValue('Preserve this draft')
  expect((await request.patch(`${api}/notebooks/${id}/cells/${cell}`, { data: { revision: doc.metadata.europa.revision, source: 'print(38)' } })).status()).toBe(200)
  await page.reload()
  await expect(page.getByLabel('Message', { exact: true })).toHaveValue('Preserve this draft')
  await expect(page.locator('.reference-chip')).toContainText('Cell 1')
  await expect(page.getByRole('button', { name: 'Send' })).toBeDisabled()
  await page.getByRole('button', { name: 'Remove cell reference' }).click()
  await expect(page.getByLabel('Message', { exact: true })).toHaveValue('Preserve this draft')
  await expect(page.getByRole('button', { name: 'Send' })).toBeEnabled()
  expect(executions).toHaveLength(0)
})
