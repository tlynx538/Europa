test('toolbar insertion and command-mode A/B preserve cell ordering', async ({ page, request }) => {
  const created = await request.post(`${api}/notebooks`, { data: { title: 'Cell insertion' } })
  expect(created.status()).toBe(201)
  const id = (await created.json()).metadata.europa.notebook_id as string
  const first = await request.post(`${api}/notebooks/${id}/cells`, { data: { revision: 1, cell_type: 'code', source: 'first = 1' } })
  expect(first.status()).toBe(201)
  const firstId = (await first.json()).cells[0].id as string
  await page.goto(`/notebooks/${id}`)
  await expect(page.locator('.cell')).toHaveCount(1)
  await page.locator('.cell').first().focus()
  await page.getByRole('toolbar', { name: 'Notebook commands' }).getByRole('button', { name: 'Insert cell' }).click()
  await expect(page.locator('.cell')).toHaveCount(2)
  await page.locator('.cell').last().focus()
  await page.keyboard.press('a')
  await expect(page.locator('.cell')).toHaveCount(3)
  await page.locator('.cell').first().focus()
  await page.keyboard.press('b')
  await expect(page.locator('.cell')).toHaveCount(4)
  const saved = await (await request.get(`${api}/notebooks/${id}`)).json()
  expect(saved.cells[0].id).toBe(firstId)
  expect(saved.cells.slice(1).map((cell: { cell_type: string }) => cell.cell_type)).toEqual(['code', 'code', 'code'])
})

test('saved table and static chart outputs stay inside the notebook canvas', async ({ page, request }) => {
  const created = await request.post(`${api}/notebooks`, { data: { title: 'Results notebook' } })
  expect(created.status()).toBe(201)
  const id = (await created.json()).metadata.europa.notebook_id as string
  const table = await request.post(`${api}/notebooks/${id}/cells`, { data: { revision: 1, cell_type: 'code', source: 'display(table)' } })
  expect(table.status()).toBe(201)
  const chart = await request.post(`${api}/notebooks/${id}/cells`, { data: { revision: 2, cell_type: 'code', source: 'display(chart)' } })
  expect(chart.status()).toBe(201)
  const document = await chart.json()
  document.cells[0].execution_count = 1
  document.cells[0].outputs = [{ output_type: 'display_data', data: { 'text/html': '<table><tr><th>Month</th><th>Value</th></tr><tr><td>Jan</td><td>42</td></tr></table>' }, metadata: {} }]
  document.cells[1].execution_count = 2
  document.cells[1].outputs = [{ output_type: 'display_data', data: { 'application/vnd.plotly.v1+json': { data: [{ type: 'bar', x: [1, 2, 3], y: [4, 7, 5] }] } }, metadata: {} }]
  const saved = await request.put(`${api}/notebooks/${id}`, { data: { revision: 3, document } })
  expect(saved.status(), await saved.text()).toBe(200)
  await page.goto(`/notebooks/${id}`)
  await expect(page.locator('.cell')).toHaveCount(2)
  await expect(page.frameLocator('iframe[title="Isolated notebook output"]').getByRole('cell', { name: '42' })).toBeVisible()
  await expect(page.getByRole('img', { name: 'Static Plotly data preview' })).toBeVisible()
  await notebookStatus(page)
  await page.screenshot({ path: resolve(process.cwd(), '../docs/screenshots/phase3f-c/table-and-chart.png'), fullPage: true })
})
