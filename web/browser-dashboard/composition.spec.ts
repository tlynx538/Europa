import { expect, test } from '../browserFixtures'
import { mkdirSync } from 'node:fs'
import { resolve } from 'node:path'

test('production Home mounts the approved dashboard', async ({ page }) => {
  await page.route('**/api/**', route => route.fulfill({ json: { path: '', items: [{ name: 'Research', type: 'directory', modified: 0, size: null }], next_cursor: null } }))
  await page.goto('/')
  await expect(page.getByRole('tab', { name: 'Files', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('button', { name: 'Research', exact: true })).toBeVisible()
})

test('Checkpoint A composition, selection, keyboard, menus and narrow layout', async ({ page }) => {
  const captures = resolve(process.env.EUROPA_CAPTURE_ROOT ? `${process.env.EUROPA_CAPTURE_ROOT}/composition` : '../docs/screenshots/phase3h/final/composition')
  mkdirSync(captures, { recursive: true })
  const capture = async (name: string) => {
    await page.evaluate(() => document.fonts.ready)
    await page.screenshot({ path: resolve(captures, `${name}.png`), fullPage: true, animations: 'disabled' })
  }
  const requests: string[] = []
  page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/')) requests.push(request.url()) })
  await page.goto('/dashboard-preview.html')
  await expect(page.getByRole('tab', { name: 'Files', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('button', { name: 'Customer Analytics Project', exact: true })).toBeVisible()
  await capture('files-desktop')
  await page.getByRole('tab', { name: 'Files', exact: true }).focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('tab', { name: 'Running', exact: true })).toBeFocused()
  await expect(page.getByRole('cell', { name: 'Unknown', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Shut down' }).first()).toBeDisabled()
  await capture('running-desktop')
  await page.keyboard.press('ArrowLeft')
  await page.getByRole('button', { name: 'Customer Analytics Project', exact: true }).click()
  await expect(page.getByRole('navigation', { name: 'Current directory' })).toContainText('Home / Customer Analytics')
  await capture('project-desktop')
  await page.getByRole('button', { name: 'Experiments', exact: true }).focus()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('button', { name: 'Reports', exact: true })).toBeFocused()
  await page.getByRole('checkbox', { name: 'Select Customer segments.ipynb', exact: true }).check()
  await page.getByRole('checkbox', { name: 'Select Revenue forecast.ipynb', exact: true }).check()
  await expect(page.getByRole('status')).toHaveText('2 selectedOpenClear')
  await expect(page.getByRole('button', { name: 'Open', exact: true })).toBeDisabled()
  await capture('selection-desktop')
  await page.getByRole('button', { name: 'New', exact: true }).click()
  await expect(page.getByRole('menuitem', { name: 'Notebook · Python 3' })).toBeVisible()
  await capture('new-menu')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'New', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Recent notebooks' }).click()
  await expect(page.getByRole('menuitem', { name: /Customer segments/ })).toContainText('Home / Customer Analytics')
  await capture('recents-menu')
  await page.keyboard.press('Escape')
  await page.getByRole('menubar').getByRole('menuitem', { name: 'File', exact: true }).click()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('menuitem', { name: 'Refresh', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Preferences', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Preferences' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Preferences', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Experiments', exact: true }).click()
  await expect(page.getByText('This folder is empty.', { exact: true })).toBeVisible()
  await capture('empty-directory')
  await page.getByRole('button', { name: 'New', exact: true }).first().click()
  await page.getByRole('menuitem', { name: 'Notebook · Python 3' }).click()
  await expect(page.getByRole('dialog')).toContainText('Home / Customer Analytics / Experiments')
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Review fixture')
  await page.getByRole('button', { name: 'Create fixture', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Review fixture.ipynb', exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Scenario' }).selectOption('loading')
  await expect(page.getByText('Loading directory…', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Review fixture.ipynb', exact: true })).toHaveCount(0)
  await capture('loading-directory')
  await page.getByRole('combobox', { name: 'Scenario' }).selectOption('empty')
  await page.getByRole('tab', { name: 'Running', exact: true }).click()
  await expect(page.getByText('No active notebook sessions.')).toBeVisible()
  await capture('empty-running')
  await page.getByRole('combobox', { name: 'Scenario' }).selectOption('error')
  await expect(page.getByRole('alert')).toContainText('Session status is Unknown')
  await capture('unavailable-running')
  await page.getByRole('combobox', { name: 'Scenario' }).selectOption('populated')
  await page.getByRole('tab', { name: 'Files', exact: true }).click()
  await page.getByRole('navigation', { name: 'Current directory' }).getByRole('button', { name: 'Customer Analytics' }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('button', { name: 'Customer segments.ipynb', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await capture('files-mobile')
  await page.getByRole('tab', { name: 'Running', exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await capture('running-mobile')
  expect(requests).toEqual([])
})
