import { test, expect, type Page } from '../browserFixtures'
import { mkdirSync } from 'node:fs'
import { join, resolve } from 'node:path'
const dir = join(process.env.EUROPA_CAPTURE_ROOT || resolve('../docs/screenshots/phase3h/final'), 'ui')
async function capture(page: Page, name: string) {
  mkdirSync(dir, { recursive: true }); await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: join(dir, name + '.png'), fullPage: true, animations: 'disabled' })
}
async function openNew(page: Page, name: string) {
  await page.getByRole('button', { name: 'New', exact: true }).first().click()
  await page.getByRole('menuitem', { name, exact: true }).click()
}

test('scripted beginner, keyboard, real workspace states and responsive/zoom acceptance', async ({ page, request }, info) => {
  test.setTimeout(150000)
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Existing', exact: true })).toBeVisible()
  await capture(page, '01-home-files')
  const files = page.getByRole('tab', { name: 'Files', exact: true })
  await files.focus(); await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('tab', { name: 'Running', exact: true })).toBeFocused()
  await page.keyboard.press('ArrowLeft'); await expect(files).toBeFocused()
  await page.getByRole('button', { name: 'New', exact: true }).first().click()
  await capture(page, '02-new-menu'); await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'New', exact: true }).first()).toBeFocused()
  await openNew(page, 'Project')
  await expect(page.getByRole('textbox', { name: 'Name', exact: true })).toBeFocused()
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Beginner project')
  await page.getByRole('button', { name: 'Create', exact: true }).click()
  await page.getByRole('button', { name: 'Beginner project Project', exact: true }).click()
  await expect(page.getByText('This folder is empty.', { exact: true })).toBeVisible()
  await capture(page, '03-empty-directory')
  await openNew(page, 'Notebook · Python 3')
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Beginner notes')
  await page.getByRole('button', { name: 'Create', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Beginner notes', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Insert cell', exact: true }).click()
  await page.locator('.cm-content').click(); await page.keyboard.insertText("print('Hello, Europa!')")
  await page.getByRole('button', { name: 'Run selected cell', exact: true }).click()
  await expect(page.locator('.outputs')).toContainText('Hello, Europa!')
  await expect(page.locator('footer.status')).toContainText('No pending receipt')
  await expect(page.locator('footer.status')).toContainText('Document saved')
  await page.getByRole('link', { name: 'Europa', exact: true }).click()
  await page.getByRole('button', { name: 'Beginner project Project', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Beginner notes.ipynb', exact: true })).toBeVisible()
  await capture(page, '04-project-directory')
  await openNew(page, 'Folder')
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Experiments')
  await page.getByRole('button', { name: 'Create', exact: true }).click()
  await page.getByRole('button', { name: 'Experiments', exact: true }).click()
  await expect(page.getByText('This folder is empty.', { exact: true })).toBeVisible()
  await capture(page, '05-nested-directory')
  await page.getByRole('navigation', { name: 'Current directory' }).getByRole('button', { name: 'Beginner project', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Beginner notes.ipynb', exact: true })).toBeVisible()
  await page.getByRole('checkbox', { name: 'Select all files', exact: true }).check()
  await expect(page.getByRole('status')).toContainText('2 selected')
  await capture(page, '06-selection')
  await page.getByRole('button', { name: 'Clear', exact: true }).click()
  await page.getByRole('button', { name: 'Recent notebooks', exact: true }).click()
  await capture(page, '07-recent-menu'); await page.keyboard.press('Escape')
  await page.getByRole('menubar').getByRole('menuitem', { name: 'Help', exact: true }).click()
  await capture(page, '08-help-menu')
  await page.getByRole('menuitem', { name: 'Keyboard shortcuts', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Keyboard shortcuts' })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('link', { name: 'Europa', exact: true }).click()
  await page.getByRole('button', { name: 'Existing', exact: true }).click()
  await page.getByRole('searchbox', { name: 'Filter files' }).fill('README')
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await page.getByRole('button', { name: 'README.md', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'File contents' })).toBeVisible()
  await capture(page, '09-text-editor')
  await page.getByRole('button', { name: 'Back to files', exact: true }).click()
  // Hold a real directory response to inspect loading without inventing repository data.
  let release!: () => void, held!: () => void
  const gate = new Promise<void>(resolve => { release = resolve }), started = new Promise<void>(resolve => { held = resolve })
  await page.route('**/api/workspace?path=Existing', async route => { const response = await route.fetch(); held(); await gate; await route.fulfill({ response }) })
  await page.getByRole('button', { name: 'Refresh', exact: true }).click(); await started
  await expect(page.getByText('Loading directory…', { exact: true })).toBeVisible()
  await capture(page, '10-loading-directory'); release(); await page.unrouteAll({ behavior: 'wait' })
  await expect(page.getByRole('button', { name: 'README.md', exact: true })).toBeVisible()
  await page.goto('/browse?path=missing-fixture-directory')
  await expect(page.getByRole('alert')).toBeVisible(); await capture(page, '11-workspace-error')
  await page.getByRole('link', { name: 'Europa', exact: true }).click()
  await page.getByRole('button', { name: 'Long filenames', exact: true }).click()
  const dimensions = []
  for (const [width, height] of [[1440, 900], [1280, 800], [768, 1024], [390, 844]]) {
    await page.setViewportSize({ width, height })
    for (const zoom of [1, 1.25, 1.5, 2]) {
      await page.evaluate(value => { document.documentElement.style.zoom = String(value) }, zoom)
      await expect.poll(() => page.evaluate(() => document.documentElement.getBoundingClientRect().right <= innerWidth + 1)).toBe(true)
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      dimensions.push(await page.evaluate(() => ({ width: innerWidth, height: innerHeight, cssZoom: getComputedStyle(document.documentElement).zoom, body: document.body.getBoundingClientRect().toJSON() })))
      if (zoom === 1 || zoom === 2) await capture(page, `responsive-${width}-${zoom * 100}`)
    }
  }
  await page.evaluate(() => { document.documentElement.style.zoom = '1' })
  await page.setViewportSize({ width: 1440, height: 900 })
  const nativeBefore = await page.evaluate(() => devicePixelRatio)
  await page.keyboard.press('ControlOrMeta+=')
  const nativeAfter = await page.evaluate(() => devicePixelRatio)
  if (nativeAfter !== nativeBefore) await page.keyboard.press('ControlOrMeta+0')
  await info.attach('responsive-and-zoom', { body: JSON.stringify({ dimensions, nativeZoomShortcutSupported: nativeBefore !== nativeAfter, method: 'CSS zoom/reflow; native shortcut probed separately' }), contentType: 'application/json' })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  expect(await page.evaluate(() => matchMedia('(prefers-reduced-motion: reduce)').matches)).toBe(true)
  await expect(page.getByRole('tablist', { name: 'Workspace views' })).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Current directory' })).toBeVisible()
  expect(await page.locator('button:visible').evaluateAll(nodes => nodes.every(node => !!(node.getAttribute('aria-label') || node.textContent?.trim())))).toBe(true)
  await info.attach('automated-semantics', { body: await page.locator('main').ariaSnapshot(), contentType: 'text/plain' })
})
